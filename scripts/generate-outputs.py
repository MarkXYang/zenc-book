#!/usr/bin/env python3
"""Pre-compute verified Zen C outputs for runnable book code blocks.

Generates theme/precomputed-outputs.js so the static HTML book (GitHub Pages,
phones, tablets, offline) can show real compiler/runtime output with zero server.
"""

import glob
import json
import os
import re
import subprocess
import tempfile
import time

ROOT_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
OUT_JS = os.path.join(ROOT_DIR, "theme", "precomputed-outputs.js")
TIMEOUT_SECS = 5
MAX_OUTPUT_CHARS = 8192


def clean_code(raw: str) -> str:
    return re.sub(r"^\s*\d+\s*\|\s?", "", raw, flags=re.M).strip()


def fnv1a_32_hex(text: str) -> str:
    """32-bit FNV-1a hash over UTF-16 code units / ASCII, matching JS implementation."""
    h = 0x811C9DC5
    for ch in text:
        h ^= ord(ch) & 0xFF
        h = (h * 0x01000193) & 0xFFFFFFFF
    return f"{h:08x}"


def is_interactive_or_unsafe(code: str) -> bool:
    # Skip snippets that block waiting on stdin or open GUI windows
    if re.search(r"\b(scanf|fgets|getchar|InitWindow|WindowShouldClose)\b", code):
        return True
    return False


def main():
    seen = {}
    blocks = []

    for path in sorted(glob.glob(os.path.join(ROOT_DIR, "*.md"))):
        with open(path, "r", encoding="utf-8") as fh:
            text = fh.read()
        for m in re.finditer(r"```zenc([^\n]*)\n(.*?)```", text, re.S):
            info = m.group(1)
            if "no_run" in info or "ignore" in info:
                continue
            code = clean_code(m.group(2))
            if not re.search(r"(^|\n)\s*(fn\s+main\s*\(|test\s+\")", code):
                continue
            key = fnv1a_32_hex(code)
            if key not in seen:
                seen[key] = True
                blocks.append((key, os.path.basename(path), code))

    print(f"Found {len(blocks)} unique runnable zenc blocks...")
    results = {}
    ok_count = 0
    skip_count = 0
    fail_count = 0

    for idx, (key, src_md, code) in enumerate(blocks, 1):
        if is_interactive_or_unsafe(code):
            skip_count += 1
            continue

        start = time.monotonic()
        with tempfile.TemporaryDirectory(prefix="zenc_pre_") as tmpdir:
            src_path = os.path.join(tmpdir, "main.zc")
            with open(src_path, "w", encoding="utf-8") as fh:
                fh.write(code)

            try:
                proc = subprocess.run(
                    ["zc", "run", "-q", src_path],
                    cwd=ROOT_DIR,
                    stdin=subprocess.DEVNULL,
                    capture_output=True,
                    text=True,
                    timeout=TIMEOUT_SECS,
                )
                elapsed_ms = int((time.monotonic() - start) * 1000)
                if proc.returncode == 0:
                    ok_count += 1
                    results[key] = {
                        "ok": True,
                        "exit_code": 0,
                        "stdout": proc.stdout[:MAX_OUTPUT_CHARS],
                        "stderr": proc.stderr[:MAX_OUTPUT_CHARS],
                        "elapsed_ms": elapsed_ms,
                    }
                else:
                    fail_count += 1
            except subprocess.TimeoutExpired:
                fail_count += 1

    with open(OUT_JS, "w", encoding="utf-8") as fh:
        fh.write("/* Auto-generated by scripts/generate-outputs.py — verified Zen C outputs */\n")
        fh.write("window.ZENC_PRECOMPUTED_OUTPUTS = ")
        json.dump(results, fh, ensure_ascii=False, separators=(",", ":"))
        fh.write(";\n")

    size_kb = os.path.getsize(OUT_JS) / 1024.0
    print(f"Done: {ok_count} cached OK, {skip_count} interactive skipped, {fail_count} non-standalone skipped.")
    print(f"Wrote {OUT_JS} ({size_kb:.1f} KB)")


if __name__ == "__main__":
    main()
